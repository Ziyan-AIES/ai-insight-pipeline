import {chromium,expect} from '@playwright/test'
const browser=await chromium.launch({headless:true})
const base=process.env.VERIFY_BASE_URL || 'https://aiinsightpipeline.netlify.app'
try {
 const context=await browser.newContext()
 const page=await context.newPage()
 const errors=[]
 page.on('pageerror',e=>errors.push(e.message))
 await page.goto(base)
 await expect(page.getByText('Synced',{exact:true})).toBeVisible({timeout:60000})
 await expect(page.getByRole('button',{name:'How it works'})).toHaveCount(0)
 await expect(page.getByRole('button',{name:'Past week',exact:true})).toBeVisible()
 await expect(page.locator('.reference-coverage')).toHaveCount(0)
 await page.locator('.reference-takeaway details').first().evaluate(el=>el.open=true)
 await page.screenshot({path:'logs/reference-layout-2026-11-16.png',fullPage:true})
 await page.getByRole('button',{name:/^Sources ·/}).click()
 const width=await page.locator('.radar-source-main').first().evaluate(el=>el.getBoundingClientRect().width)
 expect(width).toBeGreaterThan(300)
 await page.screenshot({path:'logs/visitor-sources-2026-11-16.png',fullPage:true})
 await page.getByRole('dialog',{name:'Sources'}).getByRole('button',{name:/Close/}).click()
 const selected=await page.locator('.radar-evidence-item').evaluateAll(labels=>labels.flatMap(label=>{const input=label.querySelector('input');const anchor=label.querySelector('a');return input?.checked&&anchor?.href?[anchor.href]:[]}))
 expect(selected.length).toBeGreaterThan(1)
 await context.route(url=>selected.includes(url.href),route=>route.fulfill({contentType:'text/html',body:'<title>Verified batch target</title>'}))
 await page.getByRole('button',{name:/Open selected/}).click()
 await expect.poll(()=>context.pages().length).toBe(selected.length+1)
 await expect.poll(()=>context.pages().slice(1).map(p=>p.url()).sort()).toEqual([...selected].sort())
 for(const popup of context.pages().slice(1))await popup.close()
 await page.getByRole('button',{name:'Research',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Personalization | The Next Wave of Personal Agents'})).toBeVisible()
 await page.getByRole('heading',{name:'Personalization | The Next Wave of Personal Agents'}).locator('..').getByRole('button',{name:'Explore research'}).click()
 const tabs=page.getByRole('navigation',{name:'Research sections'}).getByRole('button')
 await expect(tabs.nth(0)).toHaveText('Sources')
 await expect(tabs.nth(0)).toHaveAttribute('aria-pressed','true')
 await expect(tabs.nth(1)).toHaveText('Products')
 await page.screenshot({path:'logs/research-sources-2026-11-16.png',fullPage:true})
 await page.getByRole('combobox',{name:'Language',exact:true}).selectOption('en')
 await page.reload()
 await expect(page.getByRole('combobox',{name:'Language',exact:true})).toHaveValue('en')
 await page.screenshot({path:'logs/research-sources-2026-11-16.png',fullPage:true})
 expect(errors).toEqual([])
 console.log(JSON.stringify({checkedAt:new Date().toISOString(),sourceTextWidth:width,batchTabs:selected.length,languagePersistence:true,errors}))
}finally{await browser.close()}
